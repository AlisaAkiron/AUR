#!/usr/bin/env bash
# Generate PACKAGES.md from each package's .SRCINFO.
#
# Usage: scripts/gen-package-list.sh [--check]
#   --check  exit 1 if PACKAGES.md is out of date instead of writing it
#
# A package counts as modified from the AUR when its README.md links to
# https://aur.archlinux.org/packages/<pkgbase>.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
out="${root}/PACKAGES.md"

# Print "key<TAB>value" lines for the pkgbase section of a .SRCINFO.
# Multi-value keys (arch, pkgname) are joined with ", ".
parse_srcinfo() {
  awk -F ' = ' '
    /^pkgname = / { names = names (names ? ", " : "") $2; next }
    /^\t(pkgdesc|pkgver|pkgrel|epoch|url) = / { sub(/^\t/, "", $1); v[$1] = $2; next }
    /^\tarch = / { arch = arch (arch ? ", " : "") $2; next }
    /^pkgbase = / { base = $2 }
    END {
      printf "pkgbase\t%s\npkgname\t%s\narch\t%s\n", base, names, arch
      for (k in v) printf "%s\t%s\n", k, v[k]
    }
  ' "$1"
}

# Escape characters that would break a Markdown table cell.
md_cell() {
  local s=${1//|/\\|}
  printf '%s' "${s//$'\n'/ }"
}

generate() {
  local srcinfo dir
  local -A f
  cat <<'HEADER'
# Packages

<!-- Generated by scripts/gen-package-list.sh from each package's .SRCINFO. Do not edit by hand. -->

| Package | Version | Description | Arch | Upstream | Origin |
| --- | --- | --- | --- | --- | --- |
HEADER

  for srcinfo in "${root}"/*/.SRCINFO; do
    [[ -e "$srcinfo" ]] || continue
    dir=$(basename "$(dirname "$srcinfo")")
    f=()
    while IFS=$'\t' read -r key value; do
      f[$key]=$value
    done < <(parse_srcinfo "$srcinfo")

    local name="[${f[pkgbase]}](${dir}/)"
    # Split packages: list the produced packages under the base name
    if [[ "${f[pkgname]}" != "${f[pkgbase]}" ]]; then
      name+="<br>(${f[pkgname]})"
    fi

    local version="${f[pkgver]}-${f[pkgrel]}"
    [[ -n "${f[epoch]:-}" ]] && version="${f[epoch]}:${version}"

    local origin="Own"
    local aur="https://aur.archlinux.org/packages/${f[pkgbase]}"
    if [[ -f "${root}/${dir}/README.md" ]] && grep -qF "$aur" "${root}/${dir}/README.md"; then
      origin="Modified from [AUR](${aur}), see [changes](${dir}/README.md)"
    fi

    printf '| %s | `%s` | %s | %s | %s | %s |\n' \
      "$name" "$version" "$(md_cell "${f[pkgdesc]:-}")" "${f[arch]}" \
      "${f[url]:+<${f[url]}>}" "$origin"
  done
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$out" <(generate); then
    echo "PACKAGES.md is out of date; run scripts/gen-package-list.sh" >&2
    exit 1
  fi
else
  generate >"$out"
  echo "Wrote ${out#"${root}"/}"
fi
