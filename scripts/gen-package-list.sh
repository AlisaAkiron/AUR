#!/usr/bin/env bash
# Generate PACKAGES.md from each package's .SRCINFO.
#
# Usage: scripts/gen-package-list.sh [--check]
#   --check  exit 1 if PACKAGES.md is out of date instead of writing it
#
# A package counts as modified from the AUR when its README.md links to
# https://aur.archlinux.org/packages/<pkgbase>.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
out="${root}/PACKAGES.md"

# Print "key<TAB>value" lines for the pkgbase section of a .SRCINFO.
# Multi-value keys (arch, pkgname) are joined with ", ".
parse_srcinfo() {
  awk -F ' = ' '
    /^pkgname = / { names = names (names ? ", " : "") $2; next }
    /^\t(pkgdesc|pkgver|pkgrel|epoch|url) = / { sub(/^\t/, "", $1); v[$1] = $2; next }
    /^\tarch = / { arch = arch (arch ? ", " : "") $2; next }
    /^pkgbase = / { base = $2 }
    END {
      printf "pkgbase\t%s\npkgname\t%s\narch\t%s\n", base, names, arch
      for (k in v) printf "%s\t%s\n", k, v[k]
    }
  ' "$1"
}

# Escape text for HTML.
html() {
  local s=${1//&/&amp;}
  s=${s//</&lt;}
  s=${s//>/&gt;}
  s=${s//\"/&quot;}
  printf '%s' "${s//$'\n'/ }"
}

# An HTML table rather than a Markdown one: one cell per line keeps the
# version lines of neighbouring packages apart, so update MRs for adjacent
# packages merge without conflicts.
generate() {
  local srcinfo dir name version upstream origin aur
  local -A f
  cat <<'HEADER'
# Packages

<!-- Generated by scripts/gen-package-list.sh from each package's .SRCINFO. Do not edit by hand. -->

<table>
<thead>
<tr><th>Package</th><th>Version</th><th>Description</th><th>Arch</th><th>Upstream</th><th>Origin</th></tr>
</thead>
<tbody>
HEADER

  for srcinfo in "${root}"/*/.SRCINFO; do
    [[ -e "$srcinfo" ]] || continue
    dir=$(basename "$(dirname "$srcinfo")")
    f=()
    while IFS=$'\t' read -r key value; do
      f[$key]=$value
    done < <(parse_srcinfo "$srcinfo")

    name="<a href=\"${dir}/\">$(html "${f[pkgbase]}")</a>"
    # Split packages: list the produced packages under the base name
    if [[ "${f[pkgname]}" != "${f[pkgbase]}" ]]; then
      name+="<br>($(html "${f[pkgname]}"))"
    fi

    version="${f[pkgver]}-${f[pkgrel]}"
    [[ -n "${f[epoch]:-}" ]] && version="${f[epoch]}:${version}"

    upstream=""
    if [[ -n "${f[url]:-}" ]]; then
      upstream="<a href=\"$(html "${f[url]}")\">$(html "${f[url]}")</a>"
    fi

    origin="Own"
    aur="https://aur.archlinux.org/packages/${f[pkgbase]}"
    if [[ -f "${root}/${dir}/README.md" ]] && grep -qF "$aur" "${root}/${dir}/README.md"; then
      origin="Modified from <a href=\"${aur}\">AUR</a>, see <a href=\"${dir}/README.md\">changes</a>"
    fi

    printf '<tr>\n'
    printf '<td>%s</td>\n' "$name"
    printf '<td><code>%s</code></td>\n' "$(html "$version")"
    printf '<td>%s</td>\n' "$(html "${f[pkgdesc]:-}")"
    printf '<td>%s</td>\n' "$(html "${f[arch]}")"
    printf '<td>%s</td>\n' "$upstream"
    printf '<td>%s</td>\n' "$origin"
    printf '</tr>\n'
  done
  printf '</tbody>\n</table>\n'
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$out" <(generate); then
    echo "PACKAGES.md is out of date; run scripts/gen-package-list.sh" >&2
    exit 1
  fi
else
  generate >"$out"
  echo "Wrote ${out#"${root}"/}"
fi
